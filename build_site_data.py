def build_tracing_cards(out_dir):
    """手繪臨摹庫：由筆記 PDF 渲染整頁 WebP（已存在則略過），資料不寫出處書名"""
    import fitz
    from PIL import Image
    img_dir = os.path.join(out_dir, "tracing")
    os.makedirs(img_dir, exist_ok=True)
    doc = fitz.open(TRACING_PDF) if os.path.isfile(TRACING_PDF) else None
    cards = []
    for page_no, title, category, desc in TRACING_PAGES:
        rel = f"tracing/trace_p{page_no:03d}.webp"
        dst = os.path.join(out_dir, rel)
        if not os.path.isfile(dst) and doc is not None:
            pix = doc[page_no - 1].get_pixmap(matrix=fitz.Matrix(2.5, 2.5))
            Image.frombytes("RGB", (pix.width, pix.height), pix.samples).save(dst, "WEBP", quality=80)
        cards.append({
            "id": f"trace_p{page_no:03d}",
            "title": title,
            "category": category,
            "desc": desc,
            "source_page": f"P{page_no}",
            "image": rel
        })
    return cards

