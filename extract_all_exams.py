def main():
    print("=== 開始批次處理 24 套試題 (20 年官方真題 + 4 份名師模擬考) ===")
    
    strategy_cards = []
    
    # 1. 處理 20 年官方真題
    for y in sorted(EXAM_META.keys(), key=lambda x: int(x), reverse=True):
        meta = EXAM_META[y]
        pdf_name = f"{y}年_敷地計畫與都市設計_試題.pdf"
        pdf_path = os.path.join(EXAM_DIR, pdf_name)
        if not os.path.exists(pdf_path):
            print(f"找不到檔案: {pdf_path}")
            continue
            
        doc = fitz.open(pdf_path)
        map_page_idx = min(meta["map_page"] - 1, len(doc) - 1)
        
        # 渲染基地圖為 WebP (150 DPI)
        page = doc[map_page_idx]
        pix = page.get_pixmap(dpi=150)
        img_filename = f"map_exam_{y}.png"
        img_out_path = os.path.join(OUT_MAPS_DIR, img_filename)
        pix.save(img_out_path)
        
        # 提取題文文字
        full_text = ""
        for p in doc:
            full_text += p.get_text() + "\n"
            
        # 清理題文文字
        full_text_clean = full_text.strip()
        
        strategy_cards.append({
            "id": f"strategy_{y}",
            "year": meta["year"],
            "title": meta["title"],
            "theme": meta["theme"],
            "map_image": f"exam_maps/{img_filename}",
            "full_text": full_text_clean, # 完整題文摘要
            "challenges": meta["challenges"],
            "expert_decisions": meta["expert_decisions"],
            "diagram_hint": meta["diagram_hint"]
        })
        print(f"已完成: {meta['year']} - {meta['title']} (圖: {img_filename})")

    # 2. 處理 4 份名師模擬考
    for m in MOCK_META:
        pdf_path = os.path.join(MOCK_DIR, m["file"])
        if not os.path.exists(pdf_path):
            print(f"找不到模考: {pdf_path}")
            continue
            
        doc = fitz.open(pdf_path)
        map_page_idx = min(m["map_page"] - 1, len(doc) - 1)
        page = doc[map_page_idx]
        pix = page.get_pixmap(dpi=150)
        img_filename = f"map_{m['id']}.png"
        img_out_path = os.path.join(OUT_MAPS_DIR, img_filename)
        pix.save(img_out_path)
        
        full_text = ""
        for p in doc:
            full_text += p.get_text() + "\n"
            
        strategy_cards.append({
            "id": m["id"],
            "year": m["year"],
            "title": m["title"],
            "theme": m["theme"],
            "map_image": f"exam_maps/{img_filename}",
            "full_text": full_text.strip(),
            "challenges": m["challenges"],
            "expert_decisions": m["expert_decisions"],
            "diagram_hint": m["diagram_hint"]
        })
        print(f"已完成模考: {m['year']} - {m['title']} (圖: {img_filename})")

    print(f"\n全部 24 套試題基地圖與題文抽取完成！總共 {len(strategy_cards)} 題")
    
    # 更新 site_data.json
    json_path = os.path.join(APP_DIR, "site_data.json")
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    data["strategy_cards"] = strategy_cards
    
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"已更新 site_data.json，包含 {len(strategy_cards)} 套審題快刀題目！")

if __name__ == '__main__':
    main()
